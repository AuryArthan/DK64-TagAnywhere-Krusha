"""Prepare the supplied stereo recording for native N64 playback.
Normal ROM builds use the committed encoded asset and do not need the encoder.
Only sample-rate conversion, shared peak normalization and VADPCM are applied.
"""
from pathlib import Path
import argparse,array,hashlib,json,struct,subprocess,wave,shutil,math

def encoded(path):
    b=path.read_bytes();assert b[:4]==b'FORM' and b[8:12]==b'AIFC'
    chunks={};pos=12
    while pos+8<=len(b):
        name=b[pos:pos+4];n=struct.unpack_from('>I',b,pos+4)[0];chunks.setdefault(name,[]).append(b[pos+8:pos+8+n]);pos+=8+n+(n&1)
    appl=next(c for c in chunks[b'APPL'] if c[:4]==b'stoc' and c[5:16]==b'VADPCMCODES')
    start=5+appl[4];start+=start&1
    version,order,predictors=struct.unpack_from('>HHH',appl,start);assert (version,order,predictors)==(1,2,4)
    coefficients=struct.unpack_from('>'+str(order*predictors*8)+'h',appl,start+6)
    ssnd=chunks[b'SSND'][0];offset,block=struct.unpack_from('>II',ssnd);assert block==0
    data=ssnd[8+offset:];assert len(data)%9==0
    return data,coefficients

def main():
    repo=Path(__file__).resolve().parent.parent
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('input',type=Path)
    parser.add_argument('--encoder',type=Path,default=repo.parent/'tools/vadpcm/build/vadpcm')
    parser.add_argument('--peak-dbfs',type=float,default=-.5,help='Decoded joint-channel peak ceiling; default -0.5 dBFS.')
    args=parser.parse_args();out=repo/'assets/krusha';out.mkdir(exist_ok=True)
    if not -12<=args.peak_dbfs<=-.05:parser.error('Use a peak ceiling between -12 and -0.05 dBFS.')
    source=out/'TheScream.wav'
    if args.input.resolve()!=source.resolve():shutil.copyfile(args.input,source)
    with wave.open(str(source),'rb') as w:duration=w.getnframes()/w.getframerate();source_channels=w.getnchannels()
    pcm=out/'TheScream-stereo.wav'
    subprocess.run(['ffmpeg','-v','error','-y','-i',str(source),'-ac','2','-ar','22050','-c:a','pcm_s16le',str(pcm)],check=True)
    with wave.open(str(pcm),'rb') as w:frames=w.getnframes();rate=w.getframerate();samples=array.array('h',w.readframes(frames))
    peak=max(abs(v) for v in samples);target=math.floor(32767*10**(args.peak_dbfs/20));gain=target/max(1,peak)
    for attempt in range(8):
        channels=[]
        for index,name in enumerate(('left','right')):
            path=out/f'TheScream-{name}.wav';aifc=out/f'TheScream-{name}.aifc';decoded=out/f'TheScream-{name}-decoded.wav'
            normalized=array.array('h',(round(v*gain) for v in samples[index::2]))
            with wave.open(str(path),'wb') as w:w.setnchannels(1);w.setsampwidth(2);w.setframerate(rate);w.writeframes(normalized.tobytes())
            subprocess.run([str(args.encoder.resolve()),'encode','--dither','none','-p','4',str(path),str(aifc)],check=True)
            subprocess.run([str(args.encoder.resolve()),'decode',str(aifc),str(decoded)],check=True)
            data,coeffs=encoded(aifc)
            with wave.open(str(decoded),'rb') as w:reconstructed=array.array('h',w.readframes(w.getnframes()))
            channels.append({'name':name,'data':data,'coefficients':coeffs,'decoded_peak':max(abs(v) for v in reconstructed)})
        decoded_peak=max(c['decoded_peak'] for c in channels)
        if decoded_peak<=target:break
        gain*=target/(decoded_peak+1)
    else:raise RuntimeError('Could not fit encoded recording below the peak ceiling')
    blob=bytearray();rom=0x02100000
    text='/* Generated by build/prepare_scream.py; stereo native VADPCM. */\n'
    text+=f'#define KRUSHA_SCREAM_MICROSECONDS {(frames*1000000+rate-1)//rate+20000}\n'
    channel_meta=[]
    for c in channels:
        blob.extend(bytes((-len(blob))&15));offset=len(blob);blob.extend(c['data']);name=c['name'].upper()
        text+=f'#define KRUSHA_SCREAM_{name}_ROM 0x{rom+offset:08X}\n#define KRUSHA_SCREAM_{name}_BYTES {len(c["data"])}\n'
        channel_meta.append({'name':c['name'],'rom_address':f'0x{rom+offset:08X}','offset':offset,'adpcm_bytes':len(c['data']),'adpcm_sha256':hashlib.sha256(c['data']).hexdigest(),'decoded_peak':c['decoded_peak'],'decoded_peak_dbfs':20*math.log10(c['decoded_peak']/32768)})
    text+='#ifndef KRUSHA_SCREAM_TIMING_ONLY\n'
    for c in channels:
        text+=f'static struct {{ s32 order; s32 predictors; s16 coefficients[64]; }} scream_{c["name"]}_book __attribute__((aligned(16))) = {{\n    2, 4, {{\n'
        for i in range(0,64,8):text+='        '+', '.join(map(str,c['coefficients'][i:i+8]))+',\n'
        text+='    }\n};\n'
    text+='#endif\n';(out/'scream.h').write_text(text);(out/'TheScream.adpcm').write_bytes(blob)
    meta={'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'adpcm_sha256':hashlib.sha256(blob).hexdigest(),'header_sha256':hashlib.sha256(text.encode()).hexdigest(),'source_duration':duration,'source_channels':source_channels,'sample_rate':rate,'channels':2,'samples_per_channel':frames,'adpcm_bytes':len(blob),'rom_address':'0x02100000','encoded_channels':channel_meta,'peak_ceiling_dbfs':args.peak_dbfs,'joint_normalization_gain':gain,'native_voice_volume':32767,'encoder':'https://github.com/depp/vadpcm','encoder_commit':'413d52043a928c5fac066ccda1e69b73c7f7132b','encoder_options':['--dither','none','-p','4'],'processing':'22050 Hz stereo; shared peak normalization; native VADPCM; original stereo balance, pitch and duration; no EQ, reverb, harmonics, echoes or duplicated gain layer','mix_weights':{'provided_scream':1,'previous_roar_effect':0}}
    (out/'scream.json').write_text(json.dumps(meta,indent=2)+'\n');print(json.dumps(meta,indent=2))
if __name__=='__main__':main()
