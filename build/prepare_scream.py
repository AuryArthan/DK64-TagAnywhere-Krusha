"""Convert the supplied recording to DK64's native VADPCM; optional asset regeneration.
Normal ROM builds use the committed encoded asset and do not need the encoder.
"""
from pathlib import Path
import argparse,hashlib,json,struct,subprocess,wave,shutil

def main():
    repo=Path(__file__).resolve().parent.parent
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('input',type=Path)
    parser.add_argument('--encoder',type=Path,default=repo.parent/'tools/vadpcm/build/vadpcm')
    args=parser.parse_args();out=repo/'assets/krusha';out.mkdir(exist_ok=True)
    source=out/'TheScream.wav'
    if args.input.resolve()!=source.resolve():shutil.copyfile(args.input,source)
    with wave.open(str(source),'rb') as w:duration=w.getnframes()/w.getframerate()
    pcm=out/'TheScream-mono.wav';aifc=out/'TheScream.aifc'
    subprocess.run(['ffmpeg','-v','error','-y','-i',str(source),'-ac','1','-ar','22050','-af',f'highpass=f=20,afade=t=in:d=0.003,afade=t=out:st={duration-.015:.9f}:d=0.015','-c:a','pcm_s16le',str(pcm)],check=True)
    subprocess.run([str(args.encoder.resolve()),'encode','--dither','none','-p','4',str(pcm),str(aifc)],check=True)
    b=aifc.read_bytes();assert b[:4]==b'FORM' and b[8:12]==b'AIFC'
    chunks={};pos=12
    while pos+8<=len(b):
        name=b[pos:pos+4];n=struct.unpack_from('>I',b,pos+4)[0];chunks.setdefault(name,[]).append(b[pos+8:pos+8+n]);pos+=8+n+(n&1)
    appl=next(c for c in chunks[b'APPL'] if c[:4]==b'stoc' and c[5:16]==b'VADPCMCODES')
    start=4+1+appl[4];start+=(start&1)
    version,order,predictors=struct.unpack_from('>HHH',appl,start);assert version==1 and order==2 and predictors==4
    coefficients=struct.unpack_from('>'+str(order*predictors*8)+'h',appl,start+6)
    ssnd=chunks[b'SSND'][0];offset,block=struct.unpack_from('>II',ssnd);assert block==0
    data=ssnd[8+offset:];assert len(data)%9==0
    (out/'TheScream.adpcm').write_bytes(data)
    with wave.open(str(pcm),'rb') as w:frames=w.getnframes();rate=w.getframerate()
    text='/* Generated by build/prepare_scream.py; native VADPCM, not PCM. */\n'
    text+=f'#define KRUSHA_SCREAM_ROM 0x02100000\n#define KRUSHA_SCREAM_BYTES {len(data)}\n#define KRUSHA_SCREAM_MICROSECONDS {(frames*1000000+rate-1)//rate+20000}\n'
    text+=f'static struct {{ s32 order; s32 predictors; s16 coefficients[{len(coefficients)}]; }} scream_book = {{\n    {order}, {predictors}, {{\n'
    for i in range(0,len(coefficients),8):text+='        '+', '.join(map(str,coefficients[i:i+8]))+',\n'
    text+='    }\n};\n';(out/'scream.h').write_text(text)
    meta={'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'adpcm_sha256':hashlib.sha256(data).hexdigest(),'header_sha256':hashlib.sha256(text.encode()).hexdigest(),'source_duration':duration,'sample_rate':rate,'channels':1,'samples':frames,'adpcm_bytes':len(data),'rom_address':'0x02100000','encoder':'https://github.com/depp/vadpcm','encoder_commit':'413d52043a928c5fac066ccda1e69b73c7f7132b','encoder_options':['--dither','none','-p','4'],'processing':'22050 Hz mono; 20 Hz DC removal; 3 ms fade-in / 15 ms fade-out; original pitch and duration','mix_weights':{'provided_scream':.65,'previous_roar_effect':.35}}
    (out/'scream.json').write_text(json.dumps(meta,indent=2)+'\n')
    print(json.dumps(meta,indent=2))
if __name__=='__main__':main()
